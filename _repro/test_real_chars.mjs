const BAD_TITLE = /(短命|支撑|危局|有志无权|江湖|绰号|昏君|附身|两蹙|清后任|^军将领)/
let roleChanged = 0, titleChanged = 0, titleBad = 0, ownAsEnemy = 0
console.log('角色    定位(前→后)                徽章(前→后)')
for (const [name, title, role, camp, identity] of rows) {
  const c = { name, title, rolePosition: role, role, camp, identity, background: '' }
  normalizeCharacter(c, { isProtagonist: name === '朱由榔' })
  const rc = c.rolePosition !== role, tc = (c.title || '') !== title
  if (rc) roleChanged++
  if (tc) titleChanged++
  const t = c.title || ''
  if (BAD_TITLE.test(t)) { titleBad++; console.log('  ⚠ 徽章仍可疑:', name, t) }
  const ownSide = /主角阵营|核心/.test(camp) || /朋友/.test(camp)
  const enemyCamp = /反派|敌对|清军阵营/.test(camp)
  if (ownSide && !enemyCamp && (c.rolePosition === '反派' || c.rolePosition === '竞争对手')) {
    ownAsEnemy++; console.log('  ⚠ 己方被判对手/反派:', name, '→', c.rolePosition)
  }
  console.log(
    (name + '      ').slice(0, 7),
    ((role + ' → ' + c.rolePosition).padEnd(22)),
    ((title + ' → ' + (c.title || '(空)')))
  )
}
console.log('\n定位调整:', roleChanged, '处；徽章调整:', titleChanged, '处；徽章仍可疑:', titleBad, '；己方误判对手/反派:', ownAsEnemy)
console.log(titleBad === 0 && ownAsEnemy === 0 ? '\n=== 真实数据验证通过 ===' : '\n=== 仍有问题 ===')
