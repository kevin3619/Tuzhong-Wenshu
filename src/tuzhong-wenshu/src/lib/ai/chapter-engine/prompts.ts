/**
 * 🔥 2026-10-22 跨章公式句黑名单（引擎自算版）
 *   应用内批量流程不传 prevPhrases 时，用传入的前文正文（最近 3 章）自算：
 *   出现 ≥2 次的 9 字片段即视为「模型爱复用的公式句」，注入场景提示词禁止复用。
 *   批量脚本路径用同样的口径（在批处理侧算好后经 prevPhrases 传入）→ 两条路径同源。
 */
export function computeHistoryPhrases(text: string, topN = 26): string[] {
  const clean = String(text || '').replace(/[^一-龥A-Za-z0-9]/g, '')
  if (clean.length < 40) return []
  const cnt = new Map<string, number>()
  for (let i = 0; i + 9 <= clean.length; i++) {
    const g = clean.slice(i, i + 9)
    cnt.set(g, (cnt.get(g) || 0) + 1)
  }
  return Array.from(cnt.entries())
    .filter(e => e[1] >= 2)
    .sort((a, b) => b[1] - a[1])
    .slice(0, topN)
    .map(e => e[0])
}

