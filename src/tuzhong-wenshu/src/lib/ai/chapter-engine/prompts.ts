/** 书名 + 章号 + 章名的单行标题 */
export function titleLineOf(input: ChapterEngineInput): string {
  const book = String(input.novelTitle || '').trim()
  return (book ? book + ' · ' : '') + '第 ' + input.chapterNumber + ' 章 ' + String(input.chapterTitle || '')
}

