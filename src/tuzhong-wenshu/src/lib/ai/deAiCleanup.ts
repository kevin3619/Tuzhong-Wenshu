// 针对 Meta 叙事脚手架句（整句删除，几乎只会出现在 AI 废稿里）的低风险守卫
const SCAFFOLD_PATTERNS: RegExp[] = [
  /命运的齿轮[^。！？]*?[。！？]/g,
  /今日之事，落在[「『][^」』]*?[」』]上[。！？]?/g,
  /——明日[^。！？]*?的局[。！？]?/g,
]

// 轮转替换：同一 from 在文中多处出现时，依次使用 to 数组中的同义词，避免制造新的单一重复
function rotateReplace(text: string, from: string, to: string | string[]): string {
  if (!text || !from) return text
  if (typeof to === 'string') {
    return text.split(from).join(to)
  }
  if (to.length === 0) return text
  if (to.length === 1) return text.split(from).join(to[0])
  let out = ''
  let start = 0
  let idx: number
  let i = 0
  while ((idx = text.indexOf(from, start)) !== -1) {
    out += text.slice(start, idx) + to[i % to.length]
    i++
    start = idx + from.length
  }
  out += text.slice(start)
  return out
}

/**
 * deAiCleanup —— 确定性去AI味后处理
 * @param text 待清理的小说正文
 * @returns 已消除高频 AI 指纹词的正文（剧情/人物/字数基本不变）
 */
export function deAiCleanup(text: string): string {
  if (!text || typeof text !== 'string') return text
  let out = text

  // 1) 字典替换（短语优先，token 在后）
  for (const [from, to] of REPLACEMENTS) {
    out = rotateReplace(out, from, to)
  }

  // 2) 脚手架句整句删除
  for (const re of SCAFFOLD_PATTERNS) {
    out = out.replace(re, '')
  }

  // 3) 清理因删除产生的多余空白（多个空格/空行压缩，但保留段落换行）
  out = out.replace(/[ \t]{2,}/g, ' ')
  out = out.replace(/\n{3,}/g, '\n\n')
  out = out.replace(/[ \t]+\n/g, '\n')

  return out
}

export default deAiCleanup
